"use strict";
const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const path = require("node:path");
const code = fs.readFileSync(path.join(__dirname, "../app.js"), "utf8");
const start = code.indexOf("function normalizeAnswer(");
const end = code.indexOf("function orderedValues(", start);
assert.ok(start >= 0 && end > start);
const context = vm.createContext({});
vm.runInContext(code.slice(start, end), context);
const check = context.isAnswerCorrect;
assert.equal(check({type:"填空",answer:"3e^(-2t)"}, "3e^(-3t)"), false, "different exponents must remain different");
assert.equal(check({type:"填空",answer:"x(t-1)"}, "x(t-2)"), false, "time shifts cannot be erased");
assert.equal(check({type:"填空",answer:"−4"}, "-4"), true);
assert.equal(check({type:"填空",answer:"1,1,-2"}, "1、1、-2"), true);
assert.equal(check({type:"填空",answer:"0.25",accepted_answers:["1/4"]}, "1/4"), true);
assert.equal(check({type:"填空",answer:"0.25"}, "1/5"), false);
assert.equal(check({type:"多选",answer:"AC"}, "CA"), true);
assert.equal(check({type:"多选",answer:"AC"}, "ABC"), false);
console.log("答案判定：括号与指数保留、明确等价答案、符号和多选边界通过");
